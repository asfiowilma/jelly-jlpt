#!/usr/bin/env node
// Build data/n5/read-words.js: reading-only kana words beyond N5 for the kana stages (ticket 44,
// Q47-1). N5 has almost no words for some kana (にゃ–りょ, katakana yōon, the first katakana rows),
// so kana quizzes may also read Tanos N4/N3 words — read only: never asked for meaning, no card.
//
//   node tools/build-read-words.js <jisho-cache dir> --fetch   # fill the cache (~1 req/s, skips cached)
//   node tools/build-read-words.js <jisho-cache dir>           # write data/n5/read-words.js + summary
//
// Inputs (next to the cache): vocab-n4.json, vocab-n3.json (Tanos lists, research data).
// Candidates: katakana words, and hiragana readings with a sound N5 barely covers (ゃゅょ, the ぱ row,
// ぢ/づ). Kept only when JMdict (via the cached Jisho response, a check only: nothing copied) has an
// entry with the same word + reading, and it isn't only a suffix / prefix / counter / particle.
// Output: kana spellings only (the list's own reading), grouped by level. Generated: do not edit.
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const [cacheDir, flag] = process.argv.slice(2);
if (!cacheDir) { console.error("usage: node tools/build-read-words.js <jisho-cache dir> [--fetch]"); process.exit(2); }
const LEVELS = ["N4", "N3"];
const KATA = /^[ァ-ヺー]+$/, HIRA = /^[ぁ-ゖ]+$/, SPARSE = /[ゃゅょぱぴぷぺぽぢづ]/;

const rows = [];
LEVELS.forEach(function (lv) {
  JSON.parse(fs.readFileSync(path.resolve(cacheDir, "..", "vocab-" + lv.toLowerCase() + ".json"), "utf8")).forEach(function (e) {
    // Tanos error (playbook §1): する inside a noun's reading (心配 しんぱいする)
    if (/する$/.test(e.reading || "") && !/する$/.test(e.word)) e = Object.assign({}, e, { reading: e.reading.slice(0, -2) });
    const kana = KATA.test(e.word) ? e.word : e.reading;
    if (!kana || !(KATA.test(kana) || HIRA.test(kana) && SPARSE.test(kana))) return;
    rows.push({ word: e.word, reading: e.reading, kana: kana, level: lv });
  });
});
const cacheFile = function (q) { return path.join(cacheDir, q.replace(/[\\/:*?"<>|]/g, "_") + ".json"); };

if (flag === "--fetch") {
  const todo = Array.from(new Set(rows.map(function (r) { return r.word; }))).filter(function (q) { return !fs.existsSync(cacheFile(q)); });
  console.log(todo.length + " to fetch");
  (async function () {
    for (const q of todo) {
      for (let tries = 0; tries < 4; tries++) {
        try {
          const res = await fetch("https://jisho.org/api/v1/search/words?keyword=" + encodeURIComponent(q),
            { headers: { "User-Agent": "jelly-jlpt-author/1.0 (reading cross-check; github.com/asfiowilma/jelly-jlpt)" } });
          if (!res.ok) throw new Error("HTTP " + res.status);
          const body = await res.json();
          fs.writeFileSync(cacheFile(q), JSON.stringify({ keyword: q, fetched: new Date().toISOString(), data: body.data }));
          break;
        } catch (err) { console.error(q + ": " + err.message); await new Promise(function (r) { setTimeout(r, 5000 * (tries + 1)); }); }
      }
      await new Promise(function (r) { setTimeout(r, 1100); }); // ponytail: fixed 1.1 s throttle
    }
    console.log("done");
  })();
  return;
}

// verdict(row): '' when a JMdict entry spells row.word with row.reading (a kana word: any entry read
// so, e.g. アメリカ under 亜米利加) and has a sense that is not only a bound morpheme or a particle.
const BOUND = /^(Suffix|Prefix|Counter|Particle)/;
function verdict(r) {
  const f = cacheFile(r.word);
  if (!fs.existsSync(f)) return "not cached";
  const hits = JSON.parse(fs.readFileSync(f, "utf8")).data.filter(function (d) {
    return d.japanese.some(function (j) {
      return j.reading === r.reading && (j.word === r.word || r.word === r.reading);
    });
  });
  if (!hits.length) return "no JMdict entry with this word + reading";
  const free = hits.some(function (d) {
    return d.senses.some(function (s) { return s.parts_of_speech.length && !s.parts_of_speech.every(function (p) { return BOUND.test(p); }); });
  });
  return free ? "" : "bound morpheme or particle only";
}

const out = {}, dropped = [];
LEVELS.forEach(function (lv) { out[lv] = []; });
rows.forEach(function (r) {
  const why = verdict(r);
  if (why) return dropped.push(r.level + " " + r.word + "|" + r.reading + ": " + why);
  if (out[r.level].indexOf(r.kana) < 0) out[r.level].push(r.kana);
});
LEVELS.forEach(function (lv) { out[lv].sort(); });
const body = "// Generated by tools/build-read-words.js (do not edit by hand).\n" +
  "// Reading-only kana words beyond N5 for kana stages (ticket 44): Tanos N4/N3 lists, reading checked\n" +
  "// against JMdict. Never asked for meaning, no SRS card. Kana spellings only.\n" +
  "var KANA_READ_EXTRA = " + JSON.stringify(out, null, 0).replace(/\],"/g, '],\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}") + ";\n";
fs.writeFileSync(path.join(root, "data", "n5", "read-words.js"), body);
console.log(LEVELS.map(function (lv) { return lv + ": " + out[lv].length; }).join(", ") + "; dropped " + dropped.length);
if (process.env.VERBOSE) dropped.forEach(function (d) { console.log("  " + d); });
